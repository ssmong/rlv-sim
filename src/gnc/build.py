"""Assemble a GNCStack (guidance + navigation + control + allocation) from a resolved config.

This is the WIRING layer. It reads the Hydra config, derives the per-axis controller gains and
vehicle constants (``default_nominal``), builds the phase scheduler, and resolves the
powered-descent guidance / navigation / controller via ``hydra.utils.instantiate``: each module's
config carries a ``law._target_`` pointing at a ``build(ctx)`` factory, and ``ctx`` (a GncContext)
bundles everything a module could need. To add your own module you do NOT edit this file — you
write a ``build(ctx)`` factory and point a config group at it (see docs/adding_a_module.md).
"""

from __future__ import annotations

import numpy as np
from hydra.utils import instantiate

from core.interfaces import Phase
from gnc.context import GncContext
from gnc.guidance.aero_descent import AeroDescentGuidance
from gnc.guidance.base import as_command
from gnc.guidance.phase import SequentialPhaseScheduler, altitude_below, single_crossing
from gnc.guidance.reentry_burn import ReentryBurnGuidance
from gnc.guidance.scheduled import ScheduledGuidance
from gnc.stack import GNCStack


def _nominal_atmosphere(model: str, atm_params):
    """Host-side numpy ``(rho, a_sound)(h)`` for the configured atmosphere, so the allocation
    schedules q̄/Mach on the same model the plant integrates. This host-side scheduler avoids a
    Python/C++ call on every allocation tick; a parity test checks it against the native plant."""
    rho0 = float(atm_params.rho0)
    scale_height = float(atm_params.scale_height)

    if model == "vacuum":
        a_const = 340.3  # conventional sea-level sound speed; rho=0 disables aerodynamics

        def atmosphere(h):
            return 0.0, a_const

        return atmosphere

    if model == "exp":
        # exponential rho; a_sound from the ISA troposphere (linear lapse) capped at the tropopause.
        t0, lapse, h_trop, gamma, r_air = 288.15, 0.0065, 11000.0, 1.4, 287.05
        t_trop = t0 - lapse * h_trop  # 216.65 K

        def atmosphere(h):
            hs = max(float(h), 0.0)
            rho = rho0 * np.exp(-hs / scale_height)
            temp = t0 - lapse * hs if hs <= h_trop else t_trop
            return float(rho), float(np.sqrt(gamma * r_air * temp))

        return atmosphere

    if model == "ussa_poly":
        # US Standard Atmosphere 1976: 7 base layers in geopotential height, gradient/isothermal.
        h_base = np.array([0.0, 11000.0, 20000.0, 32000.0, 47000.0, 51000.0, 71000.0])
        lapse_l = np.array([-0.0065, 0.0, 0.001, 0.0028, 0.0, -0.0028, -0.002])
        t_base = np.array([288.15, 216.65, 216.65, 228.65, 270.65, 270.65, 214.65])
        p_base = np.array([101325.0, 22632.06, 5474.889, 868.0187, 110.9063, 66.93887, 3.956420])
        g0, r_air, gamma, r_earth = 9.80665, 287.05287, 1.4, 6356766.0
        delta_t = float(atm_params.delta_T)
        density_scale = float(atm_params.density_scale)

        def atmosphere(h):
            h_geom = max(float(h), 0.0)
            hgp = r_earth * h_geom / (r_earth + h_geom)
            idx = int(np.clip(np.sum(hgp >= h_base) - 1, 0, h_base.shape[0] - 1))
            hb, lapse_i, tb, pb = h_base[idx], lapse_l[idx], t_base[idx], p_base[idx]
            dh = hgp - hb
            temp = tb + lapse_i * dh
            if abs(lapse_i) < 1e-12:
                pres = pb * np.exp(-g0 * dh / (r_air * tb))
            else:
                pres = pb * max(temp / tb, 1e-6) ** (-g0 / (lapse_i * r_air + 1e-30))
            temp_act = max(temp + delta_t, 1.0)
            rho = density_scale * pres / (r_air * temp_act)
            return float(rho), float(np.sqrt(gamma * r_air * temp_act))

        return atmosphere

    raise ValueError(f"unknown atmosphere model {model!r}; pick vacuum|exp|ussa_poly")


def default_nominal(params, alloc, atmosphere_model: str) -> dict:
    """Build the nominal vehicle/plant constants used by GNC.

    ``alloc`` is the gnc/allocation config group (single YAML source). ``atmosphere_model`` is the
    configured environment/atmosphere tag (required, no default — a missing tag must fail loud, not
    silently schedule on the wrong air), so the allocation's q̄/Mach schedule uses the same air model
    as the plant. Controller gains are NOT here — each controller sizes its own from its config
    (see gnc/control/pd.py)."""
    n_engines = int(params.engines.positions.shape[0])
    n_gimbal = int(params.engines.tvc_bias.shape[0])
    thrust_vac_each = float(params.engines.thrust_vac[0])

    # Allocation schedules TVC authority from live thrust and mass-derived moment arm.
    x_eng = float(params.geom.x_eng)
    x_cg_wet = float(params.mass.x_cg_wet)
    x_cg_dry = float(params.mass.x_cg_dry)

    # Allocation schedules fin authority from dynamic pressure and CG-dependent arm.
    fin_arm_x = float(np.asarray(params.aero.fin_arm)[0, 0])  # axial station of fin 0 [m]
    # Representative single-fin effectiveness for the blended gimbal/fin split. Incremental fin
    # models use the mean magnitude of their Mach-scheduled slope; the geometry allocator retains
    # the full table.
    if float(params.aero.fin_incremental) > 0.5:
        fin_cla_eff = float(np.mean(np.abs(np.asarray(params.aero.fin_cla_table))))
    else:
        fin_cla_eff = float(params.aero.fin_cla)
    fin_authority_coeff = float(params.aero.fin_area) * fin_cla_eff

    # Sea-level back-pressure inputs; guidance and allocation each recompute the debit p_amb·A_e.
    p_sea = float(params.actuator.p_sea)
    a_e = float(params.engines.nozzle_exit_area[0])

    return {
        "thrust_vac": thrust_vac_each,  # per-engine (allocation)
        "p_sea": p_sea,
        "nozzle_exit_area": a_e,
        "throttle_min": float(params.engines.throttle_min[0]),
        "n_engines": n_engines,
        "n_gimbal": n_gimbal,
        "m_dry": float(params.mass.m_dry),
        "m_wet": float(params.mass.m_wet),
        "isp": float(params.engines.isp[0]),
        "g0": float(params.atmosphere.g0),
        # Gimbal moment-arm schedule inputs.
        "x_eng": x_eng,
        "x_cg_wet": x_cg_wet,
        "x_cg_dry": x_cg_dry,
        # Fin authority schedule inputs.
        "fin_arm_x": fin_arm_x,
        "fin_authority_coeff": fin_authority_coeff,
        "fin_geometry_alloc": bool(float(params.aero.fin_incremental) > 0.5),
        "fin_arm": np.asarray(params.aero.fin_arm, dtype=float),
        "fin_normal": np.asarray(params.aero.fin_normal, dtype=float),
        "fin_area": float(params.aero.fin_area),
        "fin_mach_grid": np.asarray(params.aero.fin_mach_grid, dtype=float),
        "fin_cla_table": np.asarray(params.aero.fin_cla_table, dtype=float),
        "a_sound": float(params.atmosphere.a_sound),
        "rho0": float(params.atmosphere.rho0),
        "scale_height": float(params.atmosphere.scale_height),
        # Configured-atmosphere q̄/Mach schedule: (rho, a_sound)(h) from the SAME model the plant
        # integrates (ussa_poly/exp/vacuum), replacing the hardcoded exponential in the allocation.
        "atmosphere": _nominal_atmosphere(atmosphere_model, params.atmosphere),
        "rcs_torque_scale": float(params.actuator.rcs_thrust * params.actuator.rcs_arm),
        "gimbal_limit": float(params.actuator.tvc_deflection_max_rad),
        "fin_limit": float(params.actuator.fin_deflection_max_rad),
        # Control-allocation options (gnc/allocation group; consumed by gnc.allocation.allocate).
        "fin_alloc_mode": str(alloc.powered_fin_mode),
        "fin_alloc_w_gimbal": float(alloc.blend_w_gimbal),
        "fin_alloc_w_fin": float(alloc.blend_w_fin),
        # null lockout => 0.0: q̄ < 0 never triggers, i.e. the lockout is disabled.
        "fin_qbar_lockout": (
            0.0 if alloc.fin_qbar_lockout_pa is None else float(alloc.fin_qbar_lockout_pa)
        ),
        "rcs_enabled": bool(alloc.rcs_enabled),
    }


_PHASE_NAME = {
    "reentry": int(Phase.REENTRY_BURN),
    "aero": int(Phase.AERO_DESCENT),
    "brake": int(Phase.POWERED_BRAKE),
    "powered": int(Phase.POWERED_DESCENT),
}


def build_scheduler(cfg_sched, start_phase: str):
    """Construct the latching post-flip phase scheduler from gnc/scheduler config."""
    brake = bool(cfg_sched.powered_brake)
    h_reentry_end = float(cfg_sched.reentry_end_altitude)
    h_switch = float(cfg_sched.switch_altitude)
    h_brake_end = float(cfg_sched.brake_end_altitude)
    if brake:
        phases = [
            int(Phase.REENTRY_BURN),
            int(Phase.AERO_DESCENT),
            int(Phase.POWERED_BRAKE),
            int(Phase.POWERED_DESCENT),
        ]
        thresholds = [h_reentry_end, h_switch, h_brake_end]
        if not (h_reentry_end > h_switch > h_brake_end > 0.0):
            raise ValueError(
                f"non-monotone thresholds: require reentry_end ({h_reentry_end}) > switch "
                f"({h_switch}) > brake_end ({h_brake_end}) > 0"
            )
    else:
        phases = [int(Phase.REENTRY_BURN), int(Phase.AERO_DESCENT), int(Phase.POWERED_DESCENT)]
        thresholds = [h_reentry_end, h_switch]
        if not (h_reentry_end > h_switch > 0.0):
            raise ValueError(
                f"non-monotone thresholds: require reentry_end ({h_reentry_end}) > switch "
                f"({h_switch}) > 0"
            )

    stype = str(cfg_sched.type)
    if stype == "altitude":
        guards = [altitude_below(th) for th in thresholds]
    elif stype == "guard":
        # Single-crossing guards: threshold - altitude >= 0.
        def _alt_psi(x, t, theta):
            return float(theta) - float(-np.asarray(x.r_ned)[2])

        guards = [single_crossing(_alt_psi, th) for th in thresholds]
    else:
        raise ValueError(f"unknown scheduler type: {stype}")

    if start_phase not in _PHASE_NAME:
        raise ValueError(f"unknown start_phase {start_phase!r}; pick {list(_PHASE_NAME)}")
    target = _PHASE_NAME[start_phase]
    if target not in phases:
        raise ValueError(f"start_phase={start_phase!r} requires powered_brake; not in {phases}")
    return SequentialPhaseScheduler(phases, guards, start_idx=phases.index(target))


class _PoweredCommand:
    """Wrap a powered-descent law so it may return just a bare NED thrust vector: ``phase`` and
    ``active_engines`` are injected and the attitude reference is thrust-aligned (capped at the
    config tilt). A law that returns a full Command (custom attitude / engine-off cutoff) passes
    through. Forwards ``initial_memory`` and the optional fast-rate ``track``."""

    def __init__(self, law, phase, active_engines, tilt_max_rad):
        self._law = law
        self._phase = phase
        self._active = active_engines
        self._tilt = tilt_max_rad

    def initial_memory(self):
        return self._law.initial_memory() if hasattr(self._law, "initial_memory") else {}

    def __call__(self, x_hat, t, memory):
        out, memory = self._law(x_hat, t, memory)
        return as_command(out, self._phase, self._active, self._tilt), memory

    def track(self, x_hat, t, memory):
        if hasattr(self._law, "track"):
            out, memory = self._law.track(x_hat, t, memory)
            return as_command(out, self._phase, self._active, self._tilt), memory
        return self(x_hat, t, memory)


def build_gnc(cfg, params) -> GNCStack:
    """Assemble the GNCStack: guidance + controller + allocation (all instantiate-resolved)."""
    gd = cfg.gnc.guidance  # guidance module config (gnc/guidance group)
    sched = cfg.gnc.scheduler  # phase scheduler config (gnc/scheduler group)
    nominal = default_nominal(params, cfg.gnc.allocation, str(cfg.environment.atmosphere.model))
    n_eng, t1 = nominal["n_engines"], nominal["thrust_vac"]
    start_phase = str(cfg.scenario.start_phase)
    scheduler = build_scheduler(sched, start_phase)

    reachable_phases = set(scheduler.phases[scheduler.start_idx :])

    def active_set(idx_list, phase_name, phase):
        """Build a mask and reject invalid indices for phases the scheduler can reach."""
        m = np.zeros(n_eng)
        if phase not in reachable_phases:
            return m  # scheduler latches forward, so earlier phase masks can never execute
        for i in idx_list:
            index = int(i)
            if float(i) != index or not 0 <= index < n_eng:
                raise ValueError(f"{phase_name} engine index {i!r} invalid for {n_eng} engines")
            m[index] = 1.0
        return np.asarray(m)

    reentry_active = active_set(
        sched.reentry_engines, "reentry", int(Phase.REENTRY_BURN)
    )  # center + symmetric ring pair
    brake_active = active_set(sched.brake_engines, "brake", int(Phase.POWERED_BRAKE))
    final_active = active_set(
        sched.landing_engines, "landing", int(Phase.POWERED_DESCENT)
    )  # center only
    aero_active = np.zeros(n_eng)

    def make_powered_guidance(active, phase):
        # Resolve the powered-descent law by config (gd.law._target_ -> build(ctx)) and wrap it so a
        # law may return a bare NED thrust vector (adapter adds phase/active_engines + q_ref).
        ctx = GncContext(cfg=gd, nominal=nominal, params=params, active_engines=active, phase=phase)
        tilt = float(np.deg2rad(float(gd.attitude_tilt_max_deg)))
        return _PoweredCommand(instantiate(gd.law, ctx), phase, active, tilt)

    # Phase-default laws: retro-burn (engine-first) -> aero coast (engine off) -> powered landing.
    # aero-coast params live in the guidance group but belong to the FIXED aero law, so they default
    # here (a custom powered-descent config need only carry its own keys).
    aero_guid = AeroDescentGuidance(
        aero_active,
        steer_gain=float(gd.aero_steer_gain),
        max_tilt_deg=float(gd.aero_tilt_max_deg),
    )
    powered_final = make_powered_guidance(final_active, int(Phase.POWERED_DESCENT))

    phase_guidance = {
        int(Phase.REENTRY_BURN): ReentryBurnGuidance(
            float(reentry_active.sum()) * t1, reentry_active
        ),
        int(Phase.AERO_DESCENT): aero_guid,
        int(Phase.POWERED_DESCENT): powered_final,
    }
    if bool(sched.powered_brake):
        phase_guidance[int(Phase.POWERED_BRAKE)] = make_powered_guidance(
            brake_active, int(Phase.POWERED_BRAKE)
        )

    guidance = ScheduledGuidance(scheduler, phase_guidance)
    controller = instantiate(
        cfg.gnc.control.law, GncContext(cfg=cfg.gnc.control, nominal=nominal, params=params)
    )
    return GNCStack(guidance, controller, nominal)


def build_nav(cfg):
    """Build the navigation module from gnc/navigation config (law._target_ -> build(ctx))."""
    return instantiate(cfg.gnc.navigation.law, GncContext(cfg=cfg.gnc.navigation))
